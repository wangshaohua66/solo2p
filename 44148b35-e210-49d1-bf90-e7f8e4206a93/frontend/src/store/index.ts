interface AppState {
  user: User;
  strategies: Strategy[];
  positions: Position[];
  orders: Order[];
  tickData: Record<string, TickData>;
  accountMetrics: AccountMetrics;
  riskMetrics: RiskMetrics[];
  selectedStrategyId: string | null;
  selectedSymbol: string;
  isCircuitBreakerActive: boolean;
  alerts: { id: string; type: 'info' | 'warning' | 'error' | 'success'; message: string; time: string }[];

  setSelectedStrategy: (id: string | null) => void;
  setSelectedSymbol: (symbol: string) => void;
  updateTick: (tick: TickData) => void;
  addOrder: (order: Order) => void;
  updateOrder: (order: Order) => void;
  cancelOrder: (id: string) => void;
  startStrategy: (id: string) => void;
  stopStrategy: (id: string) => void;
  updateStrategyParams: (id: string, params: Record<string, number | string | boolean>) => void;
  toggleCircuitBreaker: () => void;
  forceCloseAll: (strategyId?: string) => void;
  addAlert: (type: 'info' | 'warning' | 'error' | 'success', message: string) => void;
  dismissAlert: (id: string) => void;
}

